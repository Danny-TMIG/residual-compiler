@dataclass(frozen=True)
class Verdict:
    status: str
    reason: str
    native_count: int
    native_hits: tuple[str, ...]

    def __post_init__(self) -> None:
        allowed = {"PASS-COMPLETE", "FAIL-INCOMPLETE", "FAIL-VULN"}
        if self.status not in allowed:
            raise ValueError(f"bad status {self.status!r}")
        if self.status == "PASS-COMPLETE" and self.native_count != 0:
            raise ValueError("PASS-COMPLETE with native extensions is unrepresentable")

    @property
    def exit_code(self) -> int:
        return 0 if self.status == "PASS-COMPLETE" else 1


_FREEZE_RE = re.compile(r"^(?P<name>[A-Za-z0-9_.\-]+)==(?P<version>[^\s;]+)")


def materialize(out: Path) -> dict[str, int]:
    out.mkdir(parents=True, exist_ok=True)
    counts = {}
    for cat, names in TAXONOMY.items():
        d = out / cat
        d.mkdir(exist_ok=True)
        (d / "nodes.json").write_text(
            json.dumps(
                [{"path": f"{cat}/{n}", "category": cat, "name": n} for n in names],
                indent=2,
                sort_keys=True,
            )
        )
        counts[cat] = len(names)
    (out / "index.json").write_text(
        json.dumps(
            {"categories": counts, "total": sum(counts.values())},
            indent=2,
            sort_keys=True,
        )
    )
    return counts


def classify(freeze: Path, audit_failed: bool) -> Verdict:
    hits = []
    for line in freeze.read_text().splitlines():
        m = _FREEZE_RE.match(line.strip())
        if m and m["name"].lower() in NATIVE_EXTENSION_PACKAGES:
            hits.append(f"{m['name']}=={m['version']}")
    if audit_failed:
        return Verdict(
            "FAIL-VULN",
            "pip-audit found vulnerabilities",
            len(hits),
            tuple(sorted(hits)),
        )
    if hits:
        return Verdict(
            "FAIL-INCOMPLETE",
            "native extensions present; Ubuntu-only audit cannot see bundled C libs",
            len(hits),
            tuple(sorted(hits)),
        )
    return Verdict("PASS-COMPLETE", "audit scope == risk surface", 0, ())


def main(argv):
    p = argparse.ArgumentParser()
    sub = p.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("materialize")
    m.add_argument("--out", type=Path, default=Path("taxonomy"))
    c = sub.add_parser("classify")
    c.add_argument("freeze_file", type=Path)
    c.add_argument("--audit-failed", action="store_true")
    a = p.parse_args(argv)
    if a.cmd == "materialize":
        counts = materialize(a.out)
        print(
            f"materialized {sum(counts.values())} nodes across {len(counts)} categories"
        )
        return 0
    if a.cmd == "classify":
        v = classify(a.freeze_file, a.audit_failed)
        print(
            json.dumps(
                {
                    "status": v.status,
                    "reason": v.reason,
                    "native_count": v.native_count,
                    "native_hits": list(v.native_hits),
                },
                indent=2,
            )
        )
        return v.exit_code
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
